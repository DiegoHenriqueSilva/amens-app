import {PGlite} from '../tmp/altar-tools/node_modules/@electric-sql/pglite/dist/index.js';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const db=new PGlite();
const admin='00000000-0000-4000-8000-000000000001',member='00000000-0000-4000-8000-000000000002';
await db.exec(`
create role anon;create role authenticated;create role service_role;
create schema auth;create table auth.users(id uuid primary key);
create function auth.uid() returns uuid language sql as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
grant usage on schema auth to authenticated;
create table roles(id integer,name text);create table user_roles(user_id uuid,role_id integer);
create table altar_achievements(user_id uuid,item_id text,level integer);
insert into auth.users values('${admin}'),('${member}');
insert into roles values(1,'admin');insert into user_roles values('${admin}',1);
`);
await db.exec(await fs.readFile(new URL('../supabase/migrations/20261109010000_profile_insignias.sql',import.meta.url),'utf8'));
const as=async(id)=>{await db.exec('reset role');await db.query("select set_config('request.jwt.claim.sub',$1,false)",[id]);await db.exec('set role authenticated');};
const mine=async()=> (await db.query('select my_insignias() data')).rows[0].data;
const publicBadges=async()=> (await db.query('select public_insignias($1) data',[[member]])).rows[0].data;
await as(member);
assert.deepEqual((await mine()).eligible,[]);
await assert.rejects(db.query('select admin_supporter($1,true)',[member]),/Administrator required/);
await assert.rejects(db.query("select save_insignias(array['supporter'],true)"),/Invalid insignia/);
await assert.rejects(db.query("insert into supporter_recognitions(user_id) values($1)",[member]),/permission denied/);
await assert.rejects(db.query("select insignia_eligible($1)",[admin]),/permission denied/);
await as(admin);
await db.query('select admin_supporter($1,true)',[member]);
await as(member);
assert.deepEqual((await mine()).eligible,['supporter']);
assert.deepEqual(await publicBadges(),{},'recognition is private until user opts in');
await db.query("select save_insignias(array['supporter'],true)");
assert.deepEqual((await publicBadges())[member],{selected:['supporter'],showSupporterCard:true});
await db.exec('reset role');
await db.query("insert into altar_achievements values($1,'cross',1),($1,'candle',1),($1,'gospel',1)",[member]);
await as(member);
assert.equal((await mine()).eligible.length,4);
await assert.rejects(db.query("select save_insignias(array['supporter','supporter'],false)"),/Invalid insignia/);
await assert.rejects(db.query("select save_insignias(array['supporter','gospel','constancy','intercessor'],false)"),/Invalid insignia/);
await db.query("select save_insignias(array['supporter','gospel','intercessor'],true)");
await as(admin);
await db.query('select admin_supporter($1,false)',[member]);
assert.deepEqual((await publicBadges())[member],{selected:['gospel','intercessor'],showSupporterCard:false},'revoked support disappears immediately');
await as(member);
await db.query("select save_insignias('{}',false)");
assert.deepEqual((await publicBadges())[member],{selected:[],showSupporterCard:false});
await db.exec('reset role');
assert.equal((await db.query('select count(*)::int n from supporter_recognition_audit')).rows[0].n,2);
assert.equal((await db.query('select count(*)::int n from altar_achievements')).rows[0].n,3,'decoration never mutates awards');
assert.equal((await db.query("select has_function_privilege('anon','admin_supporter(uuid,boolean)','EXECUTE') allowed")).rows[0].allowed,false);
await db.close();
console.log('Insignia SQL passed: admin-only confirmation, ownership, eligibility, opt-in privacy, selection limits, revocation, audit and unchanged altar.');
